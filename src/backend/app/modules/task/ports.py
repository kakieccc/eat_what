from typing import Protocol

from pydantic import BaseModel

from app.modules.task.types import EventRecord, TaskClaim, TaskSnapshot


class TaskStore(Protocol):
    async def claim(self, lease_seconds: int) -> TaskClaim | None: ...
    async def renew(self, claim: TaskClaim, lease_seconds: int) -> None: ...
    async def start_step(self, claim: TaskClaim, key: str) -> None: ...
    async def save_state(self, claim: TaskClaim, state: dict[str, object], phase: str) -> None: ...
    async def append_event(self, task_id: str, event: BaseModel | dict[str, object]) -> None: ...
    async def events(self, task_id: str, after: int = 0) -> list[EventRecord]: ...
    async def latest_for_run(self, run_id: str) -> TaskSnapshot | None: ...
